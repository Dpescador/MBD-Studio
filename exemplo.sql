CREATE TABLE CLIENTE (
    ID_CLIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(180),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PEDIDO (
    ID_PEDIDO NUMBER PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    DTH_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR2(20) DEFAULT 'NOVO' NOT NULL,
    VALOR_TOTAL NUMBER(12,2),
    CONSTRAINT CK_PEDIDO_STATUS CHECK (STATUS IN ('NOVO', 'PAGO', 'CANCELADO'))
);

ALTER TABLE PEDIDO
    ADD CONSTRAINT FK_PEDIDO_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES CLIENTE (ID_CLIENTE);
